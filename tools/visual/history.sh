#!/usr/bin/env bash
# Rebuild the trajectory of the visual loop from its round history: a contact sheet of the
# reference and every round's idle keyboard in order, and a Markdown index.
#
#   tools/visual/history.sh [rounds-dir]
#
# Writes <rounds-dir>/trajectory.png (newest HISTORY_LIMIT rounds, default 11) and
# <rounds-dir>/history.md (every round). Run by round.sh after each round.
set -euo pipefail

ROUNDS=${1:-${OMNI_VISUAL_HOME:-$HOME/omniboard-visual}/rounds}
ROUNDS=$(cd "$ROUNDS" && pwd)
REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
REF="$REPO/docs/theming/reference/design-reference-01.png"
LIMIT=${HISTORY_LIMIT:-11}

mapfile -t all < <(find "$ROUNDS" -mindepth 2 -maxdepth 2 -name 01-idle.keyboard.png -printf '%h\n' | sort)
[[ ${#all[@]} -gt 0 ]] || { echo "no rounds in $ROUNDS" >&2; exit 2; }

# Older or imported rounds may lack any of these files.
field() { sed -n "s/^$2=//p" "$1/meta.txt" 2>/dev/null | head -1 || true; }
verdict() { grep -o 'VERDICT: [A-Z]*' "$1/critique.md" 2>/dev/null | tail -1 | cut -d' ' -f2 || true; }

{
    echo "# Visual loop history"
    echo
    echo "Generated by tools/visual/history.sh. Newest last. Open a round's compare-*.png for"
    echo "reference, before, after and the changed pixels; trajectory.png shows every round in order."
    echo
    echo "| Round | Change | Commit | Before | Changed (idle) | Verdict |"
    echo "|---|---|---|---|---|---|"
    for r in "${all[@]}"; do
        name=$(basename "$r")
        pct=$(sed -n 's/^01-idle changed //p' "$r/compare.txt" 2>/dev/null || true)
        echo "| $name | $(cat "$r/label.txt" 2>/dev/null) | $(field "$r" commit) | $(field "$r" before) | ${pct:--} | $(verdict "$r") |"
    done
} >"$ROUNDS/history.md"

args=(-label 'REFERENCE' "$REF")
start=$(( ${#all[@]} > LIMIT ? ${#all[@]} - LIMIT : 0 ))
for r in "${all[@]:start}"; do
    args+=(-label "$(basename "$r")\n$(cat "$r/label.txt" 2>/dev/null)" "$r/01-idle.keyboard.png")
done
magick montage "${args[@]}" -background '#000000' -fill '#9EA4BA' -pointsize 22 \
    -geometry 560x480+16+16 -tile 4x "$ROUNDS/trajectory.png"
echo "$ROUNDS/trajectory.png"
echo "$ROUNDS/history.md"
